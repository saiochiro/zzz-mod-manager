"""Generate src/shared/zzmiComponents.ts from ZZ-Model-Importer-Assets.

Maps every buffer/texture hash ZZMI publishes for an agent (all outfits) to the
part it belongs to (Hair, Body, Face, ...). The Mod Workshop uses it to split
mods into parts.

Usage: python3 scripts/gen-zzmi-components.py <ZZ-Model-Importer-Assets checkout>
"""
import json
import re
import subprocess
import sys
from pathlib import Path

assets = sys.argv[1]
root = Path(__file__).resolve().parent.parent
db_src = (root / 'src/shared/defaultHashDb.ts').read_text(encoding='utf-8')

FOLDER_OVERRIDES = {
    'jane_doe': 'Jane',
    'astra_yao': 'Astra',
    'soldier_0_anby': 'Soldier0',
    'starlight_billy': 'BillyStarlight',
    'komano_manato': 'Manato',
}


def git(*args):
    return subprocess.run(['git', '-C', assets, *args], capture_output=True, check=True, text=True).stdout


folders = [p.split('/')[-1] for p in git('ls-tree', '--name-only', 'HEAD', 'PlayerCharacterData/').split()]
agents = re.findall(r"agent_id: '(\w+)',\s*\n\s*display_name: '(?:[^'\\]|\\.)*',\s*\n\s*folder_name: '([^']+)'", db_src)

out = {}
for agent_id, folder in agents:
    base = FOLDER_OVERRIDES.get(agent_id, folder)
    # Base folder plus outfit variants (JaneSummer, MiyabiBlossom, ...). Starlight Billy is its own agent.
    variants = [f for f in folders if f == base or (f.startswith(base) and f[len(base):][:1].isupper())]
    if agent_id == 'billy_kid':
        variants = [f for f in variants if f != 'BillyStarlight']
    mapping = {}
    ambiguous = set()
    for v in variants:
        try:
            comps = json.loads(git('show', f'HEAD:PlayerCharacterData/{v}/hash.json'))
        except subprocess.CalledProcessError:
            continue
        for c in comps:
            name = re.sub(r'[^A-Za-z0-9 ]', '', c.get('component_name') or 'Other').strip() or 'Other'
            hashes = [c.get(k) for k in ('draw_vb', 'position_vb', 'blend_vb', 'texcoord_vb', 'ib')]
            for group in c.get('texture_hashes') or []:
                for tex in group:
                    if isinstance(tex, list) and len(tex) >= 3:
                        hashes.append(tex[2])
            for h in hashes:
                if h and re.fullmatch(r'[0-9a-f]{8}', h):
                    if mapping.get(h, name) != name:
                        ambiguous.add(h)  # e.g. one texture shared by Hair and Arms
                    mapping.setdefault(h, name)
    for h in ambiguous:
        mapping.pop(h, None)
    if mapping:
        out[agent_id] = mapping

# A hash claimed by two agents can't identify a part; drop those.
owners = {}
for a, m in out.items():
    for h in m:
        owners.setdefault(h, set()).add(a)
for a, m in out.items():
    for h in [h for h in m if len(owners[h]) > 1]:
        del m[h]

lines = [
    '// Generated by scripts/gen-zzmi-components.py from ZZ-Model-Importer-Assets. Do not edit by hand.',
    '// agent_id -> { hash -> part name }',
    'export const ZZMI_COMPONENTS: Record<string, Record<string, string>> = ' + json.dumps(out, separators=(',', ':'), sort_keys=True) + ';',
    '',
]
(root / 'src/shared/zzmiComponents.ts').write_text('\n'.join(lines), encoding='utf-8')
print(f'{len(out)} agents, {sum(len(m) for m in out.values())} hashes')
